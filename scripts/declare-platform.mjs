/**
 * The Declare program: prepare the site for it, and publish it.
 *
 * The program itself is compiled ahead of time (`declarec`) into
 * `declare-apps/xennic-platform/dist/`, and this script is the two steps that
 * put it in the browser's hands.
 *
 * **prepare** (before `next build`) writes the bundle's name into a small
 * generated module, so the island asks for exactly the file the build
 * produced. The name is a hash of the program's content, which is why it
 * cannot be typed by hand: a stale name would be a 404 at run time, on a page
 * that would otherwise look fine.
 *
 * **publish** (after `next build`) copies the bundle into the build's own
 * static directory, where it is served as `/_next/static/declare-platform/…`.
 *
 * That path matters. The public edge lists its public paths explicitly, and a
 * path that is not on that list is answered with a sign-in redirect instead
 * of the file — so a program served from anywhere else simply never arrives
 * for a visitor. `/_next/static/*` is already on that list, because it is
 * where the site's own build artifacts live; a compiled program belongs with
 * them. Changing the edge's list is an operation on the live edge with its
 * own reviewed hashes, and a build artifact does not deserve that.
 *
 * **dev** has no build output at all, so the bundle is copied into `public/`
 * and served from there; the development server is told which path to use
 * through the environment, and the client bundle reads it at compile time.
 *
 * Every step fails loudly rather than quietly publishing a stale program.
 */
import { createHash } from 'node:crypto'
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { spawn } from 'node:child_process'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DIST = join(ROOT, 'declare-apps', 'xennic-platform', 'dist')
const MANIFEST = join(DIST, 'manifest.json')
const GENERATED = join(ROOT, 'src', 'lib', 'declare-platform.generated.ts')
const STATIC_DIR = join(ROOT, '.next', 'static', 'declare-platform')
const DEV_STATIC_DIR = join(ROOT, 'public', 'declare-platform')

/** The name of the bundle the build produced, and the file it is. */
function readManifest() {
  if (!existsSync(MANIFEST)) {
    throw new Error(
      `no Declare manifest at ${MANIFEST}; build the program first ` +
        '(see declare-apps/xennic-platform/README.md)',
    )
  }
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'))
  if (!/^app\.[0-9a-f]+\.js$/.test(manifest.entry ?? '')) {
    throw new Error(`the Declare manifest names no bundle: ${JSON.stringify(manifest.entry)}`)
  }
  const bundle = join(DIST, manifest.entry)
  if (!existsSync(bundle)) {
    throw new Error(`the manifest names ${manifest.entry}, which is not in ${DIST}`)
  }
  return { entry: manifest.entry, bundle }
}

function generatedSource(entry) {
  return `/**
 * The Declare bundle this site was built with.
 *
 * Generated by \`scripts/declare-platform.mjs\` — do not edit by hand. The name
 * is a hash of the program's content, so it cannot be typed by hand either:
 * the file is written by the build that produced it.
 */

/** The compiled program's file name. */
export const DECLARE_PLATFORM_ENTRY = '${entry}'

/**
 * Where the program is served from.
 *
 * The build's own static directory: the public edge serves \`/_next/static/*\`
 * already, and a path outside that list is answered with a sign-in redirect
 * rather than the file.
 */
export const DECLARE_PLATFORM_PATH = \`/_next/static/declare-platform/\${DECLARE_PLATFORM_ENTRY}\`

/**
 * Where the development server serves it from: it has no build output, so the
 * file is copied into \`public/\` and served from there.
 */
export const DECLARE_PLATFORM_DEV_PATH = \`/declare-platform/\${DECLARE_PLATFORM_ENTRY}\`
`
}

/**
 * Remove the development server's copy of the program.
 *
 * The development server has no build output, so it serves the program from
 * `public/`. A production server serves `public/` from disk as well, so a
 * copy left there by a local `npm run dev` would be published on the live
 * site at a path the edge does not list — a second, unreviewed copy of the
 * program. The build removes it.
 */
function removeDevCopy() {
  if (!existsSync(DEV_STATIC_DIR)) return
  rmSync(DEV_STATIC_DIR, { recursive: true, force: true })
  console.log('declare-platform: removed the development copy')
}

function prepare() {
  const { entry } = readManifest()
  const source = generatedSource(entry)
  const existing = existsSync(GENERATED) ? readFileSync(GENERATED, 'utf8') : ''
  if (existing !== source) {
    mkdirSync(dirname(GENERATED), { recursive: true })
    writeFileSync(GENERATED, source)
    console.log(`declare-platform: prepared ${entry}`)
  } else {
    console.log(`declare-platform: already prepared for ${entry}`)
  }
  removeDevCopy()
}

function publish() {
  const { entry, bundle } = readManifest()
  if (!existsSync(join(ROOT, '.next', 'static'))) {
    throw new Error('no build output; run this after `next build`')
  }
  mkdirSync(STATIC_DIR, { recursive: true })
  copyFileSync(bundle, join(STATIC_DIR, entry))
  const digest = createHash('sha256').update(readFileSync(bundle)).digest('hex')
  console.log(`declare-platform: published ${entry} (sha256 ${digest.slice(0, 12)})`)
  removeDevCopy()
}

/**
 * `npm run dev`: the development server has no build output, so the program
 * is copied where the dev server serves it, and the island is told to ask
 * for it there. The development URL is deliberately not the production one —
 * the production path only exists after a build.
 */
function dev() {
  const { entry, bundle } = readManifest()
  mkdirSync(DEV_STATIC_DIR, { recursive: true })
  copyFileSync(bundle, join(DEV_STATIC_DIR, entry))
  // Anything after the command belongs to `next dev` — the CI starts the
  // server with `-- --hostname 127.0.0.1`, and dropping an argument the
  // caller asked for is how a server ends up listening somewhere nobody
  // expected.
  const args = [join(ROOT, 'node_modules', 'next', 'dist', 'bin', 'next'), 'dev', ...process.argv.slice(3)]
  const child = spawn(process.execPath, args, {
    cwd: ROOT,
    stdio: 'inherit',
    // The client bundle reads this at compile time; the development server
    // has no build output to publish the program from.
    env: { ...process.env, NEXT_PUBLIC_DECLARE_PLATFORM_URL: `/declare-platform/${entry}` },
  })
  child.on('exit', (code) => process.exit(code ?? 0))
}

const command = process.argv[2] ?? 'prepare'
try {
  if (command === 'prepare') prepare()
  else if (command === 'publish') publish()
  else if (command === 'dev') dev()
  else throw new Error(`unknown command: ${command}`)
} catch (error) {
  console.error(`declare-platform: ${error instanceof Error ? error.message : String(error)}`)
  process.exit(1)
}
