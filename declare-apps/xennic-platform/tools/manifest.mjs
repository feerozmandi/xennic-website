#!/usr/bin/env node
/**
 * Write the island's manifest after a `declarec` build.
 *
 * `declarec` names its bundle after a hash of the content
 * (`app.<hash>.js`), and the island in the page has to ask for that exact
 * name. Rather than parse a build log or guess, this reads the folder the
 * build just wrote and records the one entry file it contains.
 *
 * The build output lives in `dist/`, beside the program it was compiled
 * from: the compiled program is an artifact of this folder, not of the
 * website, and the website publishes it from there.
 *
 * Run from `declare-apps/xennic-platform`:
 *   node tools/manifest.mjs
 */
import { readdir, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'

// Relative to this file, so the script works from any working directory.
const OUT = resolve(import.meta.dirname, '..', 'dist')

const files = await readdir(OUT)
const entries = files.filter((name) => /^app\.[0-9a-f]+\.js$/.test(name))
if (entries.length !== 1) {
  console.error(
    `expected exactly one app.<hash>.js in ${OUT}, found ${entries.length}: ${entries.join(', ') || 'none'}`,
  )
  process.exit(1)
}

const entry = entries[0]
const manifest = {
  $comment:
    'Generated by declare-apps/xennic-platform/tools/manifest.mjs after `declarec`. Do not edit by hand.',
  entry,
  builtFrom: 'declare-apps/xennic-platform/xennic-platform.declare',
  program: 'xennic-platform',
}

await writeFile(join(OUT, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8')
console.log(`manifest: ${entry}`)
